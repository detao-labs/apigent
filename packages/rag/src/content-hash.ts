// RAG — 内容哈希（内容寻址的唯一「同一份内容」判定）
// ═══════════════════════════════════════════════════════════════════
//
// 为什么不放在 `contracts/`：那是**零重依赖**的客户端面（工具清单、字段枚举都能
// import），`node:crypto` 会把 Node 内置模块带进浏览器包（P2-8 的边界测试钉住了
// 这条）。为什么不放在 `adapters/`：**管线**也要算它（P4-6 的对账要用它把本次
// chunk 与索引里已有的行对上），而 P2-8 的 lint 规则禁止管线 import 适配器 ——
// 管线只认识端口与名字。
//
// 于是它单独成一个中立模块：写入侧（稠密 / 稀疏适配器）与对账侧（管线）都 import
// 它。**必须只有一处实现** —— 两侧算法不一致的话，同一份内容会被当成两份，复用
// 永远不命中，而且看不出任何异常。
// ═══════════════════════════════════════════════════════════════════

import { createHash } from "node:crypto";

/** 正文的 sha256（hex）。与 `knowledge_chunks.content_hash` 列的 64 字符口径一致。 */
export function contentHashOf(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex");
}
